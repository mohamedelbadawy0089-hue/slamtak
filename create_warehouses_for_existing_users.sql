-- هذا السكريبت ينشئ مخازن افتراضية للمستخدمين المسجلين مسبقاً
-- الذين ليس لديهم مخازن حتى الآن
-- ============================================================

-- إنشاء مخازن افتراضية للمستخدمين الذين ليس لديهم مخازن
INSERT INTO warehouses (
    user_id,
    warehouse_name,
    warehouse_code,
    description,
    language,
    settings
)
SELECT 
    u.id,
    'المخزن الافتراضي',
    NULL,
    'مخزن تم إنشاؤه يدوياً للمستخدم الموجود',
    'ar',
    '{}'
FROM users u
WHERE u.id NOT IN (
    SELECT user_id 
    FROM warehouses 
    WHERE user_id IS NOT NULL
);

-- عرض عدد المستخدمين الذين تم إنشاء مخازن لهم
SELECT 
    COUNT(*) as created_warehouses_count,
    'تم إنشاء مخازن افتراضية للمستخدمين الذين لم يكن لديهم مخازن' as message;
