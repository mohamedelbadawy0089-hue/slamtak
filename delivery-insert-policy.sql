-- ============================================
-- سياسة INSERT محمية - مع WITH CHECK
-- ============================================

-- سياسة الإضافة: السيرفر يرفض الإضافة إذا لم يتطابق user_id مع auth.uid()
CREATE POLICY "delivery_secure_insert" ON delivery
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);  -- ✅ يضمن مطابقة الهوية

-- ملاحظة: هذه السياسة تمنع أي محاولة للإضافة بـ user_id مختلف
-- حتى لو أرسل المستخدم user_id يدوياً في الطلب، السيرفر سيتحقق من auth.uid()
