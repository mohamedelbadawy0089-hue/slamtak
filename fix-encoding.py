#!/usr/bin/env python3
# -*- coding: utf-8 -*-

import re

def fix_arabic_encoding():
    """Fix Arabic encoding issues in products.html"""
    
    with open('products.html', 'r', encoding='utf-8') as file:
        content = file.read()
    
    # Replace question mark patterns with correct Arabic text
    replacements = {
        '???? ??? ??????': '???? ??? ?????',
        '??? ??????': '??? ??????',
        '????? ??????????': '????? ??????',
        '??? ????????': '??? ???????',
        '??? ????? ??????????': '??? ????? ????????',
        '???? ??? ??????': '???? ??? ?????',
        '???? ??? ????????': '???? ??? ???????',
        '???? ??? ??????': '???? ??? ?????',
        '???? ??? ??????': '???? ??? ?????'
    }
    
    for old_text, new_text in replacements.items():
        content = content.replace(old_text, new_text)
    
    # Also fix any remaining question mark patterns
    content = re.sub(r'\?+', '?', content)
    
    with open('products.html', 'w', encoding='utf-8') as file:
        file.write(content)
    
    print("Fixed Arabic encoding issues in products.html")

if __name__ == "__main__":
    fix_arabic_encoding()
