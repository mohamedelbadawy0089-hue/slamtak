        for _ in range(count):
            name = generate_name()
            # deduplicate
            attempts = 0
            while name in seen_names and attempts < 20:
                name = generate_name()
                attempts += 1
            seen_names.add(name)

            city = random.choice(cities)
            district = f"حي {random.randint(1, 20)}"
            address = generate_address(city, gov)
            phone = f"0{random.randint(10,19)}-{random.randint(1000000,9999999)}"

