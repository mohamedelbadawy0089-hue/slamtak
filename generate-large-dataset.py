def generate_name():
    prefix = random.choice(PHARMACY_PREFIXES)
    fn = random.choice(FIRST_NAMES)
    ln = random.choice(FIRST_NAMES)
    name = prefix.format(fn=fn, ln=ln)
    # Avoid chain names
    chain_keywords = ['العزبي', 'سيف', 'رشدي', '19011', 'علي وعلي', 'دلمار', 'عطا الله',
                      'تامر', 'علام', 'أبو علي', 'الشارقة', 'وايتس', 'دوائي', 'أوسكار',
                      'طيبة', 'صيدليات شاكر', 'الدواء', 'النجار', 'الشامي', 'الحكيم', 'الطاووس']
    for kw in chain_keywords:
        if kw in name:
            return generate_name()
    return name

def generate_address(city, gov):
    street = random.choice(STREETS)
    bnum = random.randint(1, 200)
    near = random.choice(['', 'بجوار مسجد', 'بجانب مدرسة', 'أمام بنك', 'بعد محطة المترو',
                          'عند النفق', 'أول الشارع', 'آخر الشارع', 'بجوار سوبر ماركت'])
    parts = [f"{street}، مبنى {bnum}"]
    if near:
        parts.append(near)
    parts.append(city)
    parts.append(gov)
    return "، ".join(parts)

