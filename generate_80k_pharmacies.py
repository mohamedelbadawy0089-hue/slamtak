def is_chain_pharmacy(name: str) -> bool:
    if not name:
        return True
    name_lower = name.lower()
    for chain in CHAIN_BLACKLIST:
        if chain.lower() in name_lower:
            return True
    return False

def generate_pharmacy_name() -> str:
    patterns = [
        f"{random.choice(PHARMACY_TITLES)} {random.choice(FIRST_NAMES)} {random.choice(LAST_NAMES)}",
        f"{random.choice(PHARMACY_TITLES)} {random.choice(FIRST_NAMES)} {random.choice(LAST_NAMES)}",
        f"{random.choice(PHARMACY_TITLES)} {random.choice(FIRST_NAMES)} {random.choice(LAST_NAMES)}",
        f"{random.choice(PHARMACY_TITLES)} {random.choice(FIRST_NAMES)}",
        f"{random.choice(PHARMACY_TITLES)} {random.choice(PHARMACY_NAMES_INDEPENDENT)}",
        f"{random.choice(PHARMACY_TITLES)} {random.choice(PHARMACY_NAMES_INDEPENDENT)}",
        f"صيدلية {random.choice(FIRST_NAMES)} {random.choice(LAST_NAMES)}",
    ]
    return random.choice(patterns)

def generate_address(city_data: dict) -> str:
    street = random.choice(city_data["streets"])
    building = random.randint(1, 300)
    landmarks = ["", "بجوار المسجد", "بجانب المدرسة", "أمام البنك", "بعد محطة المترو", 
                 "عند النفق", "بجوار البريد", "أمام المستشفى", "بجانب السوق", "عند الدوار"]
    landmark = random.choice(landmarks)
    
    parts = [f"{street}، مبنى {building}"]
    if landmark:
        parts.append(landmark)
    
    return "، ".join(parts)

def generate_pharmacies_for_governorate(governorate: str, count: int) -> List[Dict]:
    """توليد صيدليات لمحافظة واحدة"""
    city_data = DETAILED_LOCATIONS[governorate]
    pharmacies = []
    seen_names = set()
    
    attempts = 0
    max_attempts = count * 3  # لضمان عدم التكرار
    
    while len(pharmacies) < count and attempts < max_attempts:
        attempts += 1
        
        name = generate_pharmacy_name()
        
        # تخطي الأسماء المكررة
        if name in seen_names:
            continue
        
        # تخطي سلاسل الصيدليات
        if is_chain_pharmacy(name):
            continue
        
        seen_names.add(name)
        
        city = random.choice(city_data["cities"])
        district = random.choice(city_data["districts"])
        address = generate_address(city_data)
        
        pharmacies.append({
            "name": name,
            "address": f"{address}، {district}، {city}، {governorate}",
            "governorate": governorate,
            "city": city,
            "district": district
        })
    
    return pharmacies

def clear_table():
    """مسح الجدول القديم"""
    print("🗑️ جاري مسح البيانات القديمة...")
    headers = {
        "apikey": SUPABASE_KEY,
        "Authorization": f"Bearer {SUPABASE_KEY}",
        "Content-Type": "application/json"
    }
    url = f"{SUPABASE_URL}/rest/v1/{TABLE_NAME}"
    
    try:
        response = requests.delete(url, headers=headers, params={"is": "not.null"})
        if response.status_code in [200, 204]:
            print("   ✅ تم مسح البيانات القديمة")
        else:
            print(f"   ⚠️ لم يتم المسح (قد يكون الجدول فارغاً): {response.status_code}")
    except Exception as e:
        print(f"   ⚠️ خطأ في المسح: {e}")

def upload_batch(pharmacies: List[Dict], start_idx: int, total: int):
    """رفع دفعة واحدة"""
    if not pharmacies:
        return 0
    
    headers = {
        "apikey": SUPABASE_KEY,
        "Authorization": f"Bearer {SUPABASE_KEY}",
        "Content-Type": "application/json",
        "Prefer": "return=minimal",
        "Content-Profile": "public",
        "Accept-Profile": "public"
    }
    url = f"{SUPABASE_URL}/rest/v1/{TABLE_NAME}"
    
    try:
        response = requests.post(url, headers=headers, json=pharmacies, timeout=120)
        if response.status_code in [200, 201, 204]:
            end_idx = start_idx + len(pharmacies)
            print(f"   ✅ {end_idx:,} / {total:,}")
            return len(pharmacies)
        else:
            print(f"   ⚠️ خطأ: {response.status_code}")
            return 0
    except Exception as e:
        print(f"   ❌ استثناء: {str(e)[:100]}")
        return 0

def upload_all(pharmacies: List[Dict]):
    """رفع كل البيانات على دفعات"""
    total = len(pharmacies)
    print(f"\n☁️ جاري رفع {total:,} صيدلية...")
    
    batch_size = 1000
    uploaded = 0
    
    for i in range(0, total, batch_size):
        batch = pharmacies[i:i + batch_size]
        uploaded += upload_batch(batch, i, total)
        time.sleep(0.5)  # تأخير بين الدفعات
    
    print(f"\n🎉 تم رفع {uploaded:,} صيدلية بنجاح!")

def save_to_csv(pharmacies: List[Dict]):
    """حفظ في CSV"""
    filename = "egypt_80k_pharmacies.csv"
    with open(filename, 'w', newline='', encoding='utf-8-sig') as f:
        writer = csv.DictWriter(f, fieldnames=['name', 'address', 'governorate', 'city', 'district'])
        writer.writeheader()
        writer.writerows(pharmacies)
    print(f"💾 تم الحفظ في: {filename}")

