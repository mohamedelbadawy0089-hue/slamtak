class DistrictUpdater:
    def __init__(self):
        self.supabase: Client = create_client(SUPABASE_URL, SUPABASE_KEY)
        self.batch_size = 500  # حجم الدفعة
        self.processed = 0
        self.updated = 0
        self.errors = 0
        
    def extract_district(self, address: str, governorate: str = None, city: str = None) -> str:
        """
        استخراج المنطقة من العنوان باستخدام الكلمات المفتاحية
        """
        if not address:
            return None
            
        address_lower = address.lower()
        
        # البحث في كلمات المحافظة أولاً (أولوية أعلى)
        if governorate and governorate in DISTRICT_KEYWORDS:
            for district in DISTRICT_KEYWORDS[governorate]:
                if district.lower() in address_lower:
                    return district
        
        # البحث في كلمات المدينة
        if city and city in DISTRICT_KEYWORDS:
            for district in DISTRICT_KEYWORDS[city]:
                if district.lower() in address_lower:
                    return district
        
        # البحث في الكلمات العامة
        for district in GENERAL_DISTRICTS:
            if district.lower() in address_lower:
                return district
                
        return None
    
    def fetch_records_with_null_district(self, offset: int = 0) -> list:
        """
        جلب السجلات التي district = NULL
        """
        try:
            response = self.supabase.table(TABLE_NAME)\
                .select('id, address, governorate, city')\
                .is_('district', 'null')\
                .not_.is_('address', 'null')\
                .range(offset, offset + self.batch_size - 1)\
                .execute()
            
            return response.data if response.data else []
        except Exception as e:
            print(f"❌ Error fetching records: {e}")
            return []
    
    def update_district_batch(self, updates: list):
        """
        تحديث دفعة من السجلات
        """
        if not updates:
            return True
            
        try:
            # supabase-py لا يدعم batch update مباشرة، نستخدم RPC أو updates فردية
            for update in updates:
                self.supabase.table(TABLE_NAME)\
                    .update({'district': update['district']})\
                    .eq('id', update['id'])\
                    .execute()
                    
            return True
        except Exception as e:
            print(f"❌ Error updating batch: {e}")
            return False
    
    def process_batch(self, records: list) -> list:
        """
        معالجة دفعة واستخراج المناطق
        """
        updates = []
        
        for record in records:
            address = record.get('address', '')
            gov = record.get('governorate', '')
            city = record.get('city', '')
            
            district = self.extract_district(address, gov, city)
            
            if district:
                updates.append({
                    'id': record['id'],
                    'district': district,
                    'original_address': address[:50]  # للعرض فقط
                })
                print(f"  ✓ {record['id']}: {district} ← {address[:40]}...")
            else:
                print(f"  ✗ {record['id']}: لم يتم العثور على منطقة ← {address[:40]}...")
        
        return updates
    
    def run(self):
        """
        التشغيل الرئيسي
        """
        print("=" * 60)
        print("🚀 بدء تحديث عمود district")
        print("=" * 60)
        
        offset = 0
        batch_num = 1
        
        while True:
            print(f"\n📦 الدفعة #{batch_num} (offset: {offset})")
            print("-" * 40)
            
            # جلب السجلات
            records = self.fetch_records_with_null_district(offset)
            
            if not records:
                print("✅ لا يوجد المزيد من السجلات")
                break
            
            print(f"📥 تم جلب {len(records)} سجل")
            
            # معالجة واستخراج المناطق
            updates = self.process_batch(records)
            
            # تحديث السجلات
            if updates:
                print(f"\n📝 تحديث {len(updates)} سجل...")
                success = self.update_district_batch(updates)
                
                if success:
                    self.updated += len(updates)
                    print(f"✅ تم تحديث {len(updates)} سجل بنجاح")
                else:
                    self.errors += len(updates)
                    print(f"❌ فشل تحديث {len(updates)} سجل")
            else:
                print("ℹ️ لا يوجد تحديثات في هذه الدفعة")
            
            self.processed += len(records)
            
            # انتظار قصير لتجنب الضغط على السيرفر
            time.sleep(0.5)
            
            offset += self.batch_size
            batch_num += 1
            
            # طباعة ملخص كل 5 دفعات
            if batch_num % 5 == 0:
                self.print_summary()
        
        # الملخص النهائي
        self.print_summary(final=True)
    
    def print_summary(self, final=False):
        """
        طباعة ملخص
        """
        title = "📊 الملخص النهائي" if final else "📊 الملخص"
        print(f"\n{'=' * 60}")
        print(title)
        print(f"{'=' * 60}")
        print(f"   إجمالي المعالج: {self.processed}")
        print(f"   تم التحديث: {self.updated}")
        print(f"   الأخطاء: {self.errors}")
        print(f"   لم يتم العثور على منطقة: {self.processed - self.updated - self.errors}")
        print(f"{'=' * 60}\n")


